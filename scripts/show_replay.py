"""Print a generated replay next to the information needed to judge it.

For the most recent transcript in results/ (or the one given as argument) it shows:
  - the moment's gold label (scaffolding or rigor) and the teachers' hint,
  - the last real turns before the cut point,
  - the turns generated by the tutor and the simulated student.

Usage (from ~/socrate, venv active):
    python scripts/show_replay.py                    # latest transcript
    python scripts/show_replay.py path/to/file.json  # a specific one
    python scripts/show_replay.py --context 10       # show more real turns
"""

import argparse
import glob
import json
import os

from datasets import load_dataset

REPO = "allenai/tutormoments-preview"
REVISION = "3bb0c104d65e29facffca7ba864ef10fa22d0e78"

parser = argparse.ArgumentParser()
parser.add_argument("path", nargs="?", help="transcript JSON (default: latest in results/)")
parser.add_argument("--context", type=int, default=6, help="real turns to show before the cut")
args = parser.parse_args()

# pick the transcript: the given one, or the most recently written in results/
path = args.path
if path is None:
    files = glob.glob("results/*/transcripts/*.json")
    if not files:
        raise SystemExit("no transcripts found in results/*/transcripts/")
    path = max(files, key=os.path.getmtime)
replay = json.load(open(path))

# find the same moment in the dataset to get its label, hint and real context
moments = load_dataset(REPO, "moments", revision=REVISION)["train"]
moment = next(m for m in moments if m["id"] == replay["scenario_id"])

print("file:      ", path)
print("tutor:     ", replay.get("tutor_model"))
print("moment:    ", moment["id"])
print("gold label:", moment["dimension"].upper())
print("hint:      ", (moment.get("rubric") or {}).get("hint"))

print(f"\n--- last {args.context} real turns before the cut ---")
for turn in moment["context"][-args.context:]:
    print(f"{turn['role'].upper()}: {turn['text']}")

print("\n--- generated replay ---")
for turn in replay["generated_turns"]:
    print(f"{turn['role'].upper()}: {turn['text']}\n")
print("ended via:", replay.get("ended_via"))
